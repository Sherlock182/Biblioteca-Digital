#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

const tsconfigPath = path.join(__dirname, '../node_modules/expo-navigation-bar/tsconfig.json');

if (fs.existsSync(tsconfigPath)) {
  try {
    let content = fs.readFileSync(tsconfigPath, 'utf8');
    const tsconfig = JSON.parse(content.replace(/^\/\/.*\n/, '')); // Remove comment

    if (!tsconfig.compilerOptions.rootDir) {
      tsconfig.compilerOptions.rootDir = './src';
      
      // Rewrite with the generated comment
      const updatedContent = `// @generated by expo-module-scripts\n${JSON.stringify(tsconfig, null, 2)}\n`;
      fs.writeFileSync(tsconfigPath, updatedContent, 'utf8');
      console.log('✅ expo-navigation-bar/tsconfig.json reparado: agregado rootDir');
    }
  } catch (err) {
    console.error('❌ Error reparando expo-navigation-bar/tsconfig.json:', err.message);
  }
} else {
  console.log('⚠️ expo-navigation-bar/tsconfig.json no encontrado, saltando...');
}
