const fs = require('fs');
const path = require('path');

const expoAvTsconfigPath = path.join(__dirname, '../node_modules/expo-av/tsconfig.json');

const correctConfig = {
  extends: "expo-module-scripts/tsconfig.base",
  compilerOptions: {
    rootDir: "./src",
    outDir: "./build",
    declaration: true,
    declarationDir: "./build",
    tsBuildInfoFile: "./build/.tsbuildinfo"
  },
  include: ["./src"],
  exclude: ["**/__mocks__/*", "**/__tests__/*", "**/__rsc_tests__/*"]
};

try {
  if (fs.existsSync(expoAvTsconfigPath)) {
    fs.writeFileSync(
      expoAvTsconfigPath,
      '// @generated by expo-module-scripts\n' + JSON.stringify(correctConfig, null, 2)
    );
    console.log('✅ expo-av tsconfig.json corregido automáticamente');
  }
} catch (error) {
  console.warn('⚠️ No se pudo corregir expo-av tsconfig:', error.message);
  // No fallar si sucede un error - solo advertir
}
